# HTTP
# ---------------------------------------------------------------------------
def http_get(url: str, timeout: int = 60, description: str = "") -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "BrowserX-fetch-cef/1.0"})
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return response.read()
    except urllib.error.HTTPError as error:
        raise FetchError(f"HTTP {error.code} for {description or url}") from error
    except urllib.error.URLError as error:
        raise FetchError(f"cannot reach {url} ({error.reason})") from error
    except TimeoutError as error:
        raise FetchError(f"timeout after {timeout}s for {description or url}") from error


def http_get_json(url: str, timeout: int = 60, description: str = "") -> dict:
    payload = http_get(url, timeout=timeout, description=description)
    try:
        return json.loads(payload.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise FetchError(f"invalid JSON from {description or url}") from error


def stream_download(url: str, destination: Path, expected_sha1: str = "") -> tuple[str, int]:
    """Downloads to `destination`, returning (sha1, size)."""
    request = urllib.request.Request(url, headers={"User-Agent": "BrowserX-fetch-cef/1.0"})
    digest = hashlib.sha1()
    size = 0
    try:
        with urllib.request.urlopen(request, timeout=300) as response, destination.open("wb") as out:
            while True:
                chunk = response.read(1024 * 256)
                if not chunk:
                    break
                digest.update(chunk)
                size += len(chunk)
                out.write(chunk)
    except urllib.error.HTTPError as error:
        raise FetchError(f"HTTP {error.code} while downloading {url}") from error
    except urllib.error.URLError as error:
        raise FetchError(f"cannot reach {url} ({error.reason})") from error
    actual = digest.hexdigest()
    if expected_sha1 and actual.lower() != expected_sha1.lower():
        destination.unlink(missing_ok=True)
        raise FetchError(
            f"SHA-1 mismatch for {destination.name}\n"
            f"    expected {expected_sha1}\n    actual   {actual}\n"
            "    The download was discarded. If you pinned this build yourself, delete the\n"
            "    sha1 from cef.lock.json to re-verify from the CDN instead."
        )
    return actual, size


# ---------------------------------------------------------------------------
# Index / version resolution
# ---------------------------------------------------------------------------
def fetch_index(base: str) -> dict:
    return http_get_json(f"{base}/index.json", description="CEF version index")


def versions_for(index: dict, entry: str) -> list[str]:
    """Extracts the version list for a platform, tolerating index layout changes."""
    platform_block = index.get(entry)
    if isinstance(platform_block, dict):
        versions = platform_block.get("versions") or []
        if versions:
            return list(versions)
    # Some mirrors serve {"linux64": ["ver", ...]} directly.
    if isinstance(platform_block, list):
        return list(platform_block)
    # Last resort: any list of strings that look like CEF versions.
    for value in index.values():
        if isinstance(value, dict) and isinstance(value.get("versions"), list):
            return list(value["versions"])
    return []


def latest_stable(versions: list[str]) -> str:
    """Newest entry in the index (CEF's index is ordered oldest → newest)."""
    if not versions:
        raise FetchError("the CEF index contained no versions for this platform")
    return versions[-1]


def chromium_version_of(version: str) -> str:
    # e.g. "136.0.0+gabc1234+chromium-136.0.7103.59" -> "136.0.7103.59"
    marker = "+chromium-"
    return version.split(marker, 1)[1] if marker in version else ""


# ---------------------------------------------------------------------------
# Extraction
# ---------------------------------------------------------------------------
def _safe_members(tar: tarfile.TarFile):
    """Yields (member, relative Path) pairs, refusing path traversal."""
    for member in tar.getmembers():
        parts = PurePosixPath(member.name).parts
        if member.name.startswith("/") or ".." in parts:
            raise FetchError(f"refusing to extract unsafe path: {member.name}")
        yield member, Path(*parts)


def extract_archive(archive: Path, destination: Path) -> None:
    """Extracts a CEF distribution (tar.bz2/zip), never escaping `destination`."""
    destination.mkdir(parents=True, exist_ok=True)
    if archive.name.endswith((".tar.bz2", ".tar.gz", ".tgz", ".tar.xz")):
        with tarfile.open(archive, "r:*") as tar:
            for member, relative in _safe_members(tar):
                target = destination / relative
                if member.isdir():
                    target.mkdir(parents=True, exist_ok=True)
                elif member.isfile():
                    target.parent.mkdir(parents=True, exist_ok=True)
                    source = tar.extractfile(member)
                    if source is not None:
                        target.write_bytes(source.read())
    elif archive.suffix == ".zip":
        with zipfile.ZipFile(archive) as zipped:
            for info in zipped.infolist():
                parts = PurePosixPath(info.filename).parts
                if info.filename.startswith("/") or ".." in parts:
                    raise FetchError(f"refusing to extract unsafe path: {info.filename}")
                zipped.extract(info, destination)
    else:
        raise FetchError(f"unsupported archive type: {archive.name}")


# ---------------------------------------------------------------------------
# Header-only mode
# ---------------------------------------------------------------------------
def fetch_headers(headers_dir: Path, ref: str, chromium_ref: str, force: bool) -> None:
    """Materialises a header-only tree usable by `make check`.

    Layout produced (what the Makefile's CHECK_CEF_ROOT expects):
        .cef-headers/include/*.h        CEF's public headers
        .cef-headers/include/cef_config.h, cef_api_versions.{h,inc}
        .cef-headers/net/base/net_error_list.h
    """
    include_dir = headers_dir / "include"
    if (include_dir / "cef_app.h").is_file() and not force:
        log(f"headers already present: {headers_dir}")
        ensure_generated_headers(headers_dir, chromium_ref)
        return

    log_plan(f"fetching CEF headers from chromiumembedded/cef@{ref}")
    with tempfile.TemporaryDirectory() as temp:
        archive = Path(temp) / "cef.tar.gz"
        url = f"{CODELOAD}/chromiumembedded/cef/tar.gz/refs/heads/{ref}"
        try:
            http_get(url, timeout=180, description="CEF source tarball")
        except FetchError:
            # codeload is the fast path; the API tarball endpoint is the fallback.
            url = f"{GITHUB_API}/repos/chromiumembedded/cef/tarball/{ref}"
        archive.write_bytes(http_get(url, timeout=300, description="CEF source tarball"))
        # Extract only the *root* include/** directory, flattened:
        #   <tarball-root>/include/x.h -> .cef-headers/include/x.h
        # Anything deeper (CEF vendors test fixtures that also contain include/
        # directories) must be ignored, or a fixture would overwrite a real header.
        if include_dir.exists():
            shutil.rmtree(include_dir)
        written = 0
        root_name = ""
        with tarfile.open(archive, "r:gz") as tar:
            for member, relative in _safe_members(tar):
                parts = relative.parts
                if len(parts) < 2 or not member.isfile():
                    continue
                if not root_name:
                    root_name = parts[0]
                if parts[0] != root_name or parts[1] != "include":
                    continue
                target = headers_dir / Path(*parts[1:])
                target.parent.mkdir(parents=True, exist_ok=True)
                source = tar.extractfile(member)
                if source is None:
                    continue
                target.write_bytes(source.read())
                written += 1
        if written == 0:
            raise FetchError("the CEF tarball contained no include/ directory")
        sanity_check_headers(include_dir)

    log(f"headers extracted: {include_dir} ({count_headers(include_dir)} files)")
    ensure_generated_headers(headers_dir, chromium_ref)
    (headers_dir / "SOURCE.txt").write_text(
        "Fetched by tools/fetch_cef.py\n"
        f"cef_ref:          {ref}\n"
        f"chromium_ref:     {chromium_ref or 'main'}\n"
        f"fetched_at:       {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}\n"
        "purpose:          `make check` compile verification without the CEF binaries\n"
        "warning:          these headers are only for compile checks; `make deps` provides\n"
        "                  the matching libraries and root resources for a real build\n",
        encoding="utf-8",
    )


def count_headers(include_dir: Path) -> int:
    return sum(1 for _ in include_dir.rglob("*.h"))


def sanity_check_headers(include_dir: Path) -> None:
    """Refuses a header tree that is not usable, instead of failing later in the
    compiler with a thousand confusing errors."""
    required = ["cef_app.h", "cef_client.h", "cef_browser.h", "cef_api_hash.h"]
    for name in required:
        if not (include_dir / name).is_file():
            raise FetchError(f"header tree is incomplete: include/{name} is missing")
    markers = {
        "cef_api_hash.h": "CEF_API_VERSION",
        "cef_browser.h": "CefBrowser",
        "cef_app.h": "CefApp",
    }
    for name, marker in markers.items():
        text = (include_dir / name).read_text(encoding="utf-8", errors="replace")
        if marker not in text:
            raise FetchError(
                f"include/{name} does not look like a CEF header (missing {marker!r}).\n"
                "    This usually means the tarball layout changed; please report it."
            )
    for unexpected in ("gtest", "gmock", "cef_fixture.h"):
        if (include_dir / unexpected).exists():
            raise FetchError(f"header tree contains the upstream test fixture {unexpected!r}; refusing it")


def ensure_generated_headers(headers_dir: Path, chromium_ref: str) -> None:
    include_dir = headers_dir / "include"
    config = include_dir / "cef_config.h"
    if not config.is_file():
        config.write_text(GENERATED_CONFIG, encoding="utf-8")
        log("generated include/cef_config.h (CEF builds generate this too)")

    # cef_api_versions.h/.inc: shipped in the repo tarball; if a future ref removes
    # them, a minimal but valid pair keeps the tree compilable.
    api_versions = include_dir / "cef_api_versions.h"
    api_inc = include_dir / "cef_api_versions.inc"
    if not api_versions.is_file():
        api_versions.write_text(GENERATED_API_VERSIONS_H, encoding="utf-8")
        log("generated include/cef_api_versions.h (CEF generates this during its build)")
    if not api_inc.is_file():
        api_inc.write_text(GENERATED_API_VERSIONS_INC, encoding="utf-8")
        log("generated include/cef_api_versions.inc")

    # Chromium's error codes, needed by cef_request_handler.h.
    error_list = headers_dir / CHROMIUM_ERROR_LIST
    if not error_list.is_file():
        ref = chromium_ref or "main"
        payload = b""
        try:
            contents = http_get_json(
                f"{GITHUB_API}/repos/chromium/chromium/contents/{CHROMIUM_ERROR_LIST}?ref={ref}",
                description=CHROMIUM_ERROR_LIST,
            )
            payload = base64.b64decode(contents.get("content", ""))
        except FetchError as error:
            raise FetchError(
                f"could not fetch {CHROMIUM_ERROR_LIST} ({error}).\n"
                "    It lives in the Chromium tree; download it manually to:\n"
                f"    {error_list}"
            ) from error
        if not payload:
            raise FetchError(f"empty content while fetching {CHROMIUM_ERROR_LIST}")
        error_list.parent.mkdir(parents=True, exist_ok=True)
        error_list.write_bytes(payload)
        log(f"fetched {CHROMIUM_ERROR_LIST} ({human_bytes(len(payload))}, ref {ref})")


