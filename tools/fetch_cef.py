class FetchError(Exception):
    """Expected failure with a user-facing explanation."""


# ---------------------------------------------------------------------------
# Small helpers
# ---------------------------------------------------------------------------
def log(message: str) -> None:
    print(f"  {message}")


def log_plan(message: str) -> None:
    print(f"→ {message}")


def human_bytes(count: int) -> str:
    value = float(count)
    for unit in ("B", "KB", "MB", "GB"):
        if value < 1024 or unit == "GB":
            return f"{value:.0f} {unit}" if unit == "B" else f"{value:.1f} {unit}"
        value /= 1024
    return f"{value:.1f} GB"


# Set by --platform. Fetching a platform other than this machine's is a real case: a
# Windows build is often prepared from a Linux box (CI, or a phone-tethered laptop), and
# the name of the thing must be sayable rather than guessed from the host.
FORCED_PLATFORM = ""

# Every platform directory CEF publishes binaries for. Keeping the list here means
# --platform can reject a typo immediately instead of failing later with "no versions
# found for windows65".
KNOWN_PLATFORMS = ("linux64", "linux32", "linuxarm", "linuxarm64", "macosx64",
                   "macosarm64", "windows32", "windows64", "windowsarm64")


def platform_entry() -> str:
    """CEF's platform directory name for this machine, or the one --platform asked for."""
    if FORCED_PLATFORM:
        if FORCED_PLATFORM not in KNOWN_PLATFORMS:
            raise FetchError(f"unknown platform '{FORCED_PLATFORM}'. CEF publishes: "
                             + ", ".join(KNOWN_PLATFORMS))
        return FORCED_PLATFORM
    system = platform.system().lower()
    machine = platform.machine().lower()
    arm = machine in ("arm64", "aarch64")
    if system == "linux":
        return "linuxarm64" if arm else "linux64"
    if system == "darwin":
        return "macosarm64" if arm else "macosx64"
    if system == "windows":
        return "windowsarm64" if arm else ("windows32" if "32" in platform.architecture()[0] else "windows64")
    raise FetchError(f"unsupported platform: {system}/{machine}")


def release_type() -> str:
    """Pick the distribution flavour: standard, or minimal when requested."""
    return os.environ.get("BROWSERX_CEF_FLAVOUR", "standard")


def archive_name(version: str, entry: str, flavour: str) -> str:
    suffix = "_minimal" if flavour == "minimal" else ""
    return f"cef_binary_{version}_{entry}{suffix}.tar.bz2"


def cef_root_for(version: str, entry: str, flavour: str) -> Path:
    suffix = "_minimal" if flavour == "minimal" else ""
    return DEPS_DIR / f"cef_binary_{version}_{entry}{suffix}"


# ---------------------------------------------------------------------------
# Lock file
# ---------------------------------------------------------------------------
def load_lock() -> dict:
    if not LOCK_FILE.is_file():
        return {
            "//": "Pins the exact CEF binary distribution BrowserX builds against.",
            "//author": "BrowserX by codero-sus - https://the-codero.web.app",
            "//licence": "BrowserX is source-available (personal, non-commercial, no modification, no redistribution - see LICENSE); CEF/Chromium keep their own licences",
            "pin_mode": "track-stable",
            "platform_entry": platform_entry(),
            "version": "",
            "sha1": "",
            "size_bytes": 0,
            "cef_git_ref": "master",
        }
    return json.loads(LOCK_FILE.read_text(encoding="utf-8"))


def save_lock(lock: dict) -> None:
    """Writes the lock file, keeping every comment key (any "//" key) first and in
    its original order, so re-pinning never silently deletes documentation such as
    the author/credits lines."""
    ordered = {}
    for key, value in lock.items():          # comments first, in file order
        if key.startswith("//"):
            ordered[key] = value
    for key, value in lock.items():          # then the machine-readable values
        if not key.startswith("//"):
            ordered[key] = value
    LOCK_FILE.write_text(json.dumps(ordered, indent=2) + "\n", encoding="utf-8")


