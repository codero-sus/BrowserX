def cmd_list(base: str, entry: str, limit: int) -> int:
    index = fetch_index(base)
    versions = versions_for(index, entry)
    if not versions:
        log(f"no versions listed for {entry}")
        return 1
    log_plan(f"CEF builds available for {entry} ({len(versions)}; newest {limit})")
    for version in versions[-limit:]:
        chromium = chromium_version_of(version)
        log(f"{version}{('  (Chromium ' + chromium + ')') if chromium else ''}")
    return 0


def cmd_download(args, lock: dict, entry: str, flavour: str, base: str) -> int:
    existing = os.environ.get("BROWSERX_CEF_DIR")
    if existing:
        root = Path(existing)
        if not (root / "include" / "cef_app.h").is_file():
            raise FetchError(f"BROWSERX_CEF_DIR={existing} has no include/cef_app.h")
        log_plan(f"using BROWSERX_CEF_DIR: {root}")
        log("nothing to download")
        return 0

    version = args.version or lock.get("version") or ""
    if not version:
        log_plan("no pinned version yet — resolving the newest stable build")
        version = latest_stable(versions_for(fetch_index(base), entry))
    elif lock.get("pin_mode") == "track-stable" and args.update:
        newest = latest_stable(versions_for(fetch_index(base), entry))
        if newest != version:
            log_plan(f"re-pinning {version} -> {newest}")
            lock["sha1"] = ""
            lock["size_bytes"] = 0
            version = newest

    root = cef_root_for(version, entry, flavour)
    if (root / "include" / "cef_app.h").is_file() and not args.force:
        log_plan(f"already installed: {root}")
        log("use --force to re-download")
        return 0

    filename = archive_name(version, entry, flavour)
    expected_sha1 = "" if args.version or args.update else lock.get("sha1", "")
    local_archive = Path(args.archive or os.environ.get("BROWSERX_CEF_ARCHIVE", "")) if (
        args.archive or os.environ.get("BROWSERX_CEF_ARCHIVE")
    ) else None

    DEPS_DIR.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=str(DEPS_DIR)) as temp:
        archive = local_archive or Path(temp) / filename
        if local_archive:
            log_plan(f"installing from local archive: {local_archive}")
            if not local_archive.is_file():
                raise FetchError(f"archive not found: {local_archive}")
            sha1 = sha1_of(local_archive)
            size = local_archive.stat().st_size
            if expected_sha1 and sha1.lower() != expected_sha1.lower():
                raise FetchError(
                    f"SHA-1 mismatch for {local_archive.name}\n"
                    f"    expected {expected_sha1}\n    actual   {sha1}"
                )
        else:
            url = args.url or os.environ.get("BROWSERX_CEF_URL") or (
                f"{base}/{version}/{filename}" if args.version_dir else f"{base}/{filename}"
            )
            log_plan(f"downloading {url}")
            sha1, size = stream_download(url, archive, expected_sha1)
            log(f"verified SHA-1 {sha1} ({human_bytes(size)})")

        log_plan(f"extracting into {DEPS_DIR}")
        extract_archive(archive, DEPS_DIR)

    if not (root / "include" / "cef_app.h").is_file():
        # The tarball's top-level directory name can differ from our guess.
        candidates = sorted(
            path for path in DEPS_DIR.glob("cef_binary_*") if (path / "include" / "cef_app.h").is_file()
        )
        if not candidates:
            raise FetchError("extraction finished but no CEF layout was found")
        root = candidates[-1]
        log(f"using extracted root: {root}")

    previous_comments = {key: value for key, value in lock.items() if key.startswith("//")}
    lock.update(
        {
            "platform_entry": entry,
            "pin_mode": lock.get("pin_mode", "track-stable"),
            "platform_entry": entry,
            "version": version,
            "sha1": sha1,
            "size_bytes": size,
            "chromium_version": chromium_version_of(version),
            "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        }
    )
    lock.update(previous_comments)  # never lose the docs on a re-pin; update wins
    save_lock(lock)
    log(f"lock file updated: {LOCK_FILE.name}")
    log("")
    log(f"  CEF root : {root}")
    log(f"  next     : make        (build) / make run (launch)")
    return 0


def sha1_of(path: Path) -> str:
    digest = hashlib.sha1()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 256), b""):
            digest.update(chunk)
    return digest.hexdigest()


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------
def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        prog="tools/fetch_cef.py",
        description="Download, verify and extract the CEF build BrowserX links against.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--update", action="store_true", help="resolve the newest stable build and re-pin cef.lock.json")
    parser.add_argument("--list", action="store_true", help="list the versions available upstream")
    parser.add_argument("--headers-only", action="store_true", help="fetch only the CEF headers (for `make check`)")
    parser.add_argument("--print-path", action="store_true", help="print the CEF root that would be used and exit")
    parser.add_argument("--version", default="", help="install this exact CEF version (overrides the lock)")
    parser.add_argument("--platform", default="",
                        help="fetch for this platform instead of this machine's "
                             f"({', '.join(KNOWN_PLATFORMS)})")
    parser.add_argument("--version-dir", action="store_true", help="use the per-version CDN path layout")
    parser.add_argument("--archive", default="", help="install from a local tar.bz2/zip instead of downloading")
    parser.add_argument("--url", default="", help="download exactly this URL (still SHA-1 verified)")
    parser.add_argument("--dir", default="", help="install directory (default: .cef-deps)")
    parser.add_argument("--headers-dir", default="", help="header tree location (default: .cef-headers)")
    parser.add_argument("--ref", default="", help="git ref for --headers-only (default: the lock's cef_git_ref)")
    parser.add_argument("--limit", type=int, default=12, help="how many versions --list prints")
    parser.add_argument("--force", action="store_true", help="re-download even when the tree already exists")
    parser.add_argument("--json", action="store_true", help="machine-readable summary")
    argv, pasted_note = argv_notes.strip_trailing_comment(argv)
    if pasted_note:
        print(f"note: {pasted_note}", file=sys.stderr)
    args = parser.parse_args(argv)
    if args.platform:
        # Set before anything calls platform_entry(): the lock file, the archive name and
        # the install directory all derive from it.
        globals()["FORCED_PLATFORM"] = args.platform

    global DEPS_DIR
    if args.dir:
        DEPS_DIR = Path(args.dir).expanduser().resolve()
    headers_dir = Path(args.headers_dir).expanduser().resolve() if args.headers_dir else (
        Path(os.environ["BROWSERX_CEF_HEADERS"]).expanduser().resolve()
        if os.environ.get("BROWSERX_CEF_HEADERS")
        else HEADERS_DIR
    )

    lock = load_lock()
    host_entry = platform_entry()
    locked_entry = lock.get("platform_entry") or ""
    if args.platform:
        entry = host_entry
        if locked_entry and locked_entry != entry:
            log_plan(f"fetching {entry} (--platform); cef.lock.json records "
                     f"{locked_entry}, whose SHA-1 does not apply to this archive")
            lock["sha1"] = ""
            lock["size_bytes"] = 0
    elif locked_entry and locked_entry != host_entry:
        # Do not silently download the wrong platform's build, and do not silently ignore
        # a committed pin either: say what is happening and why.
        if lock.get("pin_mode") == "hard":
            raise FetchError(
                f"cef.lock.json pins {locked_entry} and is in 'hard' pin mode, but this "
                f"machine builds {host_entry}. Pass --platform {locked_entry} to fetch the "
                "pinned build, or change pin_mode to 'track-stable' in cef.lock.json.")
        log_plan(f"cef.lock.json was pinned on {locked_entry}; this machine builds "
                 f"{host_entry}, so this fetch resolves and pins that instead")
        entry = host_entry
        lock["sha1"] = ""
        lock["size_bytes"] = 0
    else:
        entry = locked_entry or host_entry
    flavour = release_type()
    base = (os.environ.get("BROWSERX_CEF_BASE") or DEFAULT_BASE).rstrip("/")

    print()
    print("  BrowserX — CEF acquisition")
    print("  " + "-" * 60)

    try:
        if args.list:
            return cmd_list(base, entry, args.limit)

        if args.print_path:
            version = args.version or lock.get("version") or "<unpinned>"
            print(str(cef_root_for(version, entry, flavour)))
            return 0

        if args.headers_only:
            ref = args.ref or lock.get("cef_git_ref") or "master"
            fetch_headers(headers_dir, ref, lock.get("chromium_version", ""), args.force)
            print()
            log(f"  headers : {headers_dir}")
            log("  next    : make check")
            print()
            return 0

        status = cmd_download(args, lock, entry, flavour, base)
        if args.json:
            print(json.dumps(lock, indent=2))
        print()
        return status
    except FetchError as error:
        print()
        print(f"  ✘ {error}")
        print()
        print("  Things that can help:")
        print("    • offline?  make deps BROWSERX_CEF_ARCHIVE=/path/cef_binary_*.tar.bz2")
        print("    • already have CEF?  export BROWSERX_CEF_DIR=/path/cef_binary_*")
        print("    • different mirror?  export BROWSERX_CEF_BASE=https://your.mirror")
        print("    • only need compile checks?  make headers")
        print()
        return 2
    except KeyboardInterrupt:
        print("\n  interrupted — nothing was pinned\n")
        return 130


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
