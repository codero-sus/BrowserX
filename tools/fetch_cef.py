"""BrowserX — CEF acquisition.

Downloads, verifies and extracts the Chromium Embedded Framework distribution the
browser links against, so `make deps` is a single reproducible command.

Design rules:
  * **stdlib only.** No pip, no requests, no cmake. If Python 3 runs, this runs.
  * **Never trust a download.** Every archive is SHA-1 verified against the value
    in cef.lock.json before a single byte is extracted, and the lock file is only
    written after a successful verification.
  * **Work offline.** `--archive FILE` (or BROWSERX_CEF_ARCHIVE) installs from a
    tar.bz2/zip you already have; BROWSERX_CEF_DIR uses an existing distribution
    untouched.
  * **Be honest about failure.** If the CEF CDN is unreachable the script explains
    exactly which command produces which file, instead of a traceback.

Usage:
    tools/fetch_cef.py                  download + verify + extract (pinned)
    tools/fetch_cef.py --update         resolve newest stable and re-pin the lock
    tools/fetch_cef.py --list           show the versions available upstream
    tools/fetch_cef.py --headers-only   fetch just the CEF headers (compile checks)
    tools/fetch_cef.py --print-path     print the CEF root that would be used

Environment overrides:
    BROWSERX_CEF_DIR       use this distribution (skips downloading)
    BROWSERX_CEF_ARCHIVE   install from this local archive
    BROWSERX_CEF_URL       download exactly this URL (still SHA-1 checked)
    BROWSERX_CEF_BASE      different CDN base (mirrors, offline caches)
    BROWSERX_CEF_HEADERS   header tree location (default: <repo>/.cef-headers)
"""

