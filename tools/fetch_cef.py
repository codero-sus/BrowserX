FIXTURE_2016 = REPO_ROOT / "tests" / "fixtures" / "cef_index_record_2016.json"
FIXTURE_2026 = REPO_ROOT / "tests" / "fixtures" / "cef_index_windows64_2026.json"
MODERN = "146.0.11+g4d5e6f7+chromium-146.0.7680.31"
OLDER = "145.0.8+g1a2b3c4+chromium-145.0.7632.75"


def self_test() -> int:
    failures = 0

    def expect(condition: bool, label: str) -> None:
        nonlocal failures
        print(f"    {'✔' if condition else '✘'} {label}")
        failures += not condition

    print("  self-test")

    record = json.loads(FIXTURE_2016.read_text())
    expect(record["cef_version"] == "3.2704.1414.g185cd6c",
           "the captured 2016 record loads")
    expect(not looks_like_version(record),
           "a whole index record is not a version (the guard that stops the bad URL)")
    try:
        require_version(record)
        expect(False, "require_version refuses the record")
    except FetchError as error:
        expect("not a version" in str(error), "require_version refuses the record")
    expect(require_version(MODERN) == MODERN, "a real version passes require_version")

    # The layout that broke it: one platform, a list of records, newest first.
    modern_record = {"cef_version": MODERN, "channel": "stable", "files": [
        {"name": f"cef_binary_{MODERN}_windows64.tar.bz2", "sha1": "1" * 40,
         "size": 260000000, "type": "standard"},
        {"name": f"cef_binary_{MODERN}_windows64_minimal.tar.bz2", "sha1": "2" * 40,
         "size": 100000000, "type": "minimal"},
    ]}
    index = {"windows64": {"versions": [modern_record,
                                       {"cef_version": OLDER, "channel": "stable", "files": []},
                                       record]}}
    versions = versions_for(index, "windows64")
    expect(versions == [MODERN, OLDER, record["cef_version"]],
           "records are flattened into version strings, in order")
    expect(latest_stable(versions) == MODERN,
           "the newest wins, not the last one in the list")
    expect(record["cef_version"] not in newest_first(versions)[:2],
           "the 2016 build is not chosen again")

    # Other shapes, so a layout change is a test failure rather than a surprise.
    expect(latest_stable(versions_for({"linux64": [OLDER, MODERN]}, "linux64")) == MODERN,
           "a plain list of strings still resolves")
    expect(latest_stable(versions_for({"linux64": {"versions": [OLDER, MODERN]}}, "linux64")) == MODERN,
           "a list nested under versions still resolves")
    expect(latest_stable(versions_for({"macosx64": {OLDER: {"channel": "stable"},
                                                   MODERN: {"channel": "stable"}}}, "macosx64")) == MODERN,
           "a mapping of version to details still resolves")

    # Ordering, including the trap: 2016's "3.2704" is smaller than today's "146.0".
    expect(cef_version_key("3.2704.1414.g185cd6c") < cef_version_key("146.0.11+g4d5e6f7"),
           "3.2704 (Chromium 51) sorts below 146.0, as it should")
    expect(cef_version_key("10.0.9999") > cef_version_key("10.0.1000"),
           "numbers are compared as numbers, not as text")
    expect(cef_version_key(MODERN) == (146, 0, 11),
           "build metadata after the plus is ignored when ordering")
    expect(cef_tree_version_key("cef_binary_154.0.34+x_windows64") == (154, 0, 34),
           "a distribution directory sorts by its version numbers")
    expect(cef_tree_version_key("cef_binary_154.0.34+x_windows64")
           > cef_tree_version_key("cef_binary_99.0.1+x_windows64_beta"),
           "99 does not beat 154 by being sorted as text")

    # A record's own file list: exact name and SHA-1, so the archive is not guessed.
    picked = pick_file(entry_for(index, "windows64", record["cef_version"]),
                       "windows64", "standard")
    expect(picked.get("name") == "cef_binary_3.2704.1414.g185cd6c_windows64.tar.bz2",
           "the file for a platform and flavour comes from the index")
    expect(picked.get("sha1") == "a5c09cfd51f236a227caee8c8839d98038fbc23a",
           "its published SHA-1 comes from the index too")
    minimal = pick_file(entry_for(index, "windows64", record["cef_version"]),
                        "windows64", "minimal")
    expect(minimal.get("type") == "minimal", "the minimal flavour picks the minimal file")

    # The whole download path, offline: the URL it builds has to be a URL. The network
    # and the disk are stubbed; the logic is the real thing, including the resolution,
    # the file the index names, and the SHA-1 it is verified against. This is the shape
    # of the original failure, where a JSON record ended up inside the URL.
    stubbed = {name: globals()[name] for name in
               ("http_get_json", "stream_download", "extract_archive", "save_lock", "DEPS_DIR")}
    seen: dict[str, str] = {}
    mixed = {"windows64": {"versions": [
        {"cef_version": "999.0.1+g0badc0d+chromium-999.0.1.1", "channel": "beta", "files": [
            {"name": "cef_binary_999.0.1+g0badc0d+chromium-999.0.1.1_windows64_beta.tar.bz2",
             "sha1": "9" * 40, "type": "standard"}]},
        modern_record,
        record]}}

    def fake_get_json(url: str, timeout: int = 60, description: str = "") -> dict:
        return mixed

    def fake_download(url: str, destination: Path, expected_sha1: str = "") -> tuple[str, int]:
        seen["url"], seen["sha1"] = url, expected_sha1
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(b"archive")
        return "0" * 40, 7

    def fake_extract(archive: Path, destination: Path) -> None:
        root = destination / archive.name.replace(".tar.bz2", "")
        (root / "include").mkdir(parents=True, exist_ok=True)
        (root / "include" / "cef_app.h").write_text("// stub")

    try:
        globals()["http_get_json"] = fake_get_json
        globals()["stream_download"] = fake_download
        globals()["extract_archive"] = fake_extract
        globals()["save_lock"] = lambda lock: None
        with tempfile.TemporaryDirectory() as scratch:
            globals()["DEPS_DIR"] = Path(scratch)
            args = argparse.Namespace(version="", update=False, force=False, archive="",
                                      url="", version_dir=False)
            code = cmd_download(args, {"pin_mode": "track-stable", "platform_entry": "linux64",
                                       "version": "", "sha1": ""}, "windows64", "standard",
                                "https://cef-builds.example")
    finally:
        for name, value in stubbed.items():
            globals()[name] = value

    expect(code == 0, "a fetch with no pin completes against the stubbed index")
    expect("beta" not in seen.get("url", "") and "999.0.1" not in seen.get("url", ""),
           "a pre-release is never what gets downloaded, even when it is newest")
    expect(seen.get("url", "").count("{") == 0 and MODERN in seen.get("url", ""),
           "the URL it downloads is a URL containing the resolved version")
    expect(seen.get("sha1", "") == "1" * 40,
           "and it is verified against the SHA-1 the index published for that file")
    expect(seen.get("url", "").endswith(f"cef_binary_{MODERN}_windows64.tar.bz2"),
           "using the exact file name the index published, not a guessed one")

    # The real index as of 2026-10-16, with a beta line above the stable one. This is
    # the failure that reached a Windows machine: the newest entry was a beta build.
    real = json.loads(FIXTURE_2026.read_text())["windows64"]
    records = version_records(real, "windows64")
    chosen, note = choose_record(records, "windows64", "standard")
    expect(chosen["version"].startswith("154.0.34"),
           "the newest released build is chosen, not the newest build")
    expect("156.0.7" in note and "beta" in note,
           "and it says which pre-release it skipped, and why")
    expect(len(records) == 4, "the index's own records are read (4 versions in the fixture)")

    beta_only = {"windows64": {"versions": [
        {"cef_version": MODERN, "channel": "beta", "files": [
            {"name": f"cef_binary_{MODERN}_windows64_dev.tar.bz2", "sha1": "3" * 40,
             "type": "standard"}]}]}}
    chosen, note = choose_record(version_records(beta_only, "windows64"), "windows64", "standard")
    expect(chosen["version"] == MODERN and "no released build" in note,
           "with nothing but pre-releases it uses one, and says so rather than pretending")

    label, why = pre_release({"cef_version": MODERN, "channel": "dev", "files": [
        {"name": f"cef_binary_{MODERN}_windows64.tar.bz2", "type": "standard"}]},
        "windows64", "standard")
    expect(label == "dev" and "dev" in why,
           "a channel field is honoured even when the file names look ordinary")

    label, why = pre_release(records[0], "windows64", "standard")
    expect(label == "beta" and "beta" in why,
           "a beta archive is recognised by its file name too")
    plain = pick_file({"files": [
        {"name": f"cef_binary_{MODERN}_windows64_beta.tar.bz2", "type": "standard"},
        {"name": f"cef_binary_{MODERN}_windows64.tar.bz2", "type": "standard"}]},
        "windows64", "standard")
    expect(plain.get("name") == f"cef_binary_{MODERN}_windows64.tar.bz2",
           "a release archive is preferred over a pre-release one for the same version")

    # Pruning: the beta tree a wrong fetch left behind is 1.4 GB, and the only thing
    # that will ever remove it is this. It must remove that one and nothing else.
    with tempfile.TemporaryDirectory() as scratch:
        deps = Path(scratch) / ".cef-deps"
        keep = deps / "cef_binary_154.0.34+g14c5a08+chromium-154.0.8037.98_windows64"
        keep_beta = deps / "cef_binary_156.0.7+g47dbc1d+chromium-156.0.8078.17_windows64_beta"
        other_platform = deps / "cef_binary_154.0.34+g14c5a08+linux64"
        for tree in (keep, keep_beta, other_platform):
            (tree / "include").mkdir(parents=True, exist_ok=True)
            (tree / "include" / "cef_app.h").write_text("")
            (tree / "blob.bin").write_bytes(b"x" * 2048)
        real_deps = DEPS_DIR
        try:
            globals()["DEPS_DIR"] = deps
            lock = {"version": "154.0.34+g14c5a08+chromium-154.0.8037.98"}
            args = argparse.Namespace(apply=False)
            expect(cmd_prune(args, lock, "windows64", "standard") == 0,
                   "a dry run of --prune succeeds")
            expect(keep_beta.is_dir(), "a dry run removes nothing")
            args = argparse.Namespace(apply=True)
            cmd_prune(args, lock, "windows64", "standard")
            expect(keep.is_dir(), "the pinned tree survives --prune")
            expect(not keep_beta.exists(), "the pre-release tree is removed")
            expect(other_platform.is_dir(),
                   "another platform's tree is left alone (it was fetched deliberately)")
            expect(cmd_prune(argparse.Namespace(apply=True),
                             {"version": ""}, "windows64", "standard") == 0,
                   "with nothing pinned, --prune refuses to guess and removes nothing")
        finally:
            globals()["DEPS_DIR"] = real_deps

    # Nothing readable: a clear error, never a download attempt.
    try:
        latest_stable(versions_for({"windows64": {"versions": [{"unknown": "shape"}]}}, "windows64"))
        expect(False, "an unreadable index is refused with advice")
    except FetchError as error:
        expect("--version" in str(error), "an unreadable index is refused with advice")

    print()
    if failures:
        print(f"  {failures} self-test failure(s)\n")
        return 1
    print("  self-test passed\n")
    return 0


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------
def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        prog="tools/fetch_cef.py",
        description="Download, verify and extract the CEF build BrowserX links against.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--update", action="store_true", help="resolve the newest stable build and re-pin cef.lock.json")
    parser.add_argument("--list", action="store_true", help="list the versions available upstream (newest first, marked if a pre-release)")
    parser.add_argument("--headers-only", action="store_true", help="fetch only the CEF headers (for `make check`)")
    parser.add_argument("--print-path", action="store_true", help="print the CEF root that would be used and exit")
    parser.add_argument("--version", default="", help="install this exact CEF version (overrides the lock)")
    parser.add_argument("--platform", default="",
                        help="fetch for this platform instead of this machine's "
                             f"({', '.join(KNOWN_PLATFORMS)})")
    parser.add_argument("--version-dir", action="store_true", help="use the per-version CDN path layout")
    parser.add_argument("--archive", default="", help="install from a local tar.bz2/zip instead of downloading")
    parser.add_argument("--url", default="", help="download exactly this URL (still SHA-1 verified)")
    parser.add_argument("--dir", default="", help="install directory (default: .cef-deps)")
    parser.add_argument("--headers-dir", default="", help="header tree location (default: .cef-headers)")
    parser.add_argument("--ref", default="", help="git ref for --headers-only (default: the lock's cef_git_ref)")
    parser.add_argument("--limit", type=int, default=12, help="how many versions --list prints")
    parser.add_argument("--force", action="store_true", help="re-download even when the tree already exists")
    parser.add_argument("--json", action="store_true", help="machine-readable summary")
    parser.add_argument("--self-test", action="store_true",
                        help="check the version resolution offline, no download")
    parser.add_argument("--prune", action="store_true",
                        help="list extracted CEF trees that are not the pinned one")
    parser.add_argument("--apply", action="store_true",
                        help="with --prune: actually remove them")
    argv, pasted_note = argv_notes.strip_trailing_comment(argv)
    if pasted_note:
        print(f"note: {pasted_note}", file=sys.stderr)
    args = parser.parse_args(argv)
    if args.platform:
        # Set before anything calls platform_entry(): the lock file, the archive name and
        # the install directory all derive from it.
        globals()["FORCED_PLATFORM"] = args.platform

    global DEPS_DIR
    if args.dir:
        DEPS_DIR = Path(args.dir).expanduser().resolve()
    headers_dir = Path(args.headers_dir).expanduser().resolve() if args.headers_dir else (
        Path(os.environ["BROWSERX_CEF_HEADERS"]).expanduser().resolve()
        if os.environ.get("BROWSERX_CEF_HEADERS")
        else HEADERS_DIR
    )

    if args.self_test:
        return self_test()

    lock = load_lock()
    host_entry = platform_entry()
    locked_entry = lock.get("platform_entry") or ""
    if args.platform:
        entry = host_entry
        if locked_entry and locked_entry != entry:
            log_plan(f"fetching {entry} (--platform); cef.lock.json records "
                     f"{locked_entry}, whose SHA-1 does not apply to this archive")
            lock["sha1"] = ""
            lock["size_bytes"] = 0
    elif locked_entry and locked_entry != host_entry:
        # Do not silently download the wrong platform's build, and do not silently ignore
        # a committed pin either: say what is happening and why.
        if lock.get("pin_mode") == "hard":
            raise FetchError(
                f"cef.lock.json pins {locked_entry} and is in 'hard' pin mode, but this "
                f"machine builds {host_entry}. Pass --platform {locked_entry} to fetch the "
                "pinned build, or change pin_mode to 'track-stable' in cef.lock.json.")
        log_plan(f"cef.lock.json was pinned on {locked_entry}; this machine builds "
                 f"{host_entry}, so this fetch resolves and pins that instead")
        entry = host_entry
        lock["sha1"] = ""
        lock["size_bytes"] = 0
    else:
        entry = locked_entry or host_entry
    flavour = release_type()
    base = (os.environ.get("BROWSERX_CEF_BASE") or DEFAULT_BASE).rstrip("/")

    print()
    print("  BrowserX — CEF acquisition")
    print("  " + "-" * 60)

    try:
        if args.prune:
            return cmd_prune(args, lock, entry, flavour)

        if args.list:
            return cmd_list(base, entry, args.limit, flavour)

        if args.print_path:
            version = args.version or lock.get("version") or "<unpinned>"
            print(str(cef_root_for(version, entry, flavour)))
            return 0

        if args.headers_only:
            ref = args.ref or lock.get("cef_git_ref") or "master"
            fetch_headers(headers_dir, ref, lock.get("chromium_version", ""), args.force)
            print()
            log(f"  headers : {headers_dir}")
            log("  next    : make check")
            print()
            return 0

        status = cmd_download(args, lock, entry, flavour, base)
        if args.json:
            print(json.dumps(lock, indent=2))
        print()
        return status
    except FetchError as error:
        print()
        print(f"  ✘ {error}")
        print()
        print("  Things that can help:")
        print("    • offline?  make deps BROWSERX_CEF_ARCHIVE=/path/cef_binary_*.tar.bz2")
        print("    • already have CEF?  export BROWSERX_CEF_DIR=/path/cef_binary_*")
        print("    • different mirror?  export BROWSERX_CEF_BASE=https://your.mirror")
        print("    • only need compile checks?  make headers")
        print()
        return 2
    except KeyboardInterrupt:
        print("\n  interrupted — nothing was pinned\n")
        return 130


if __name__ == "__main__":
    # Windows console code pages cannot encode ✔ or →; without this a tool dies while
    # reporting something else. Best effort: it never makes a working run fail.
    import utf8_console  # same directory: sys.path[0] when run as a script
    utf8_console.enable()
    sys.exit(main(sys.argv[1:]))
